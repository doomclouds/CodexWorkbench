import { mkdir, readFile, writeFile, unlink, copyFile, readdir, realpath } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { dirname, join, resolve, isAbsolute } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { sdkProtocolDebugPlugin } from './app-sdk-debug.mjs';

const root = fileURLToPath(new URL('../plugins/agentero-studio/', import.meta.url));
const requirePlugin = createRequire(`${root}package.json`);
const { build, transform } = await import(pathToFileURL(requirePlugin.resolve('esbuild')).href);
const { build: viteBuild } = await import(pathToFileURL(requirePlugin.resolve('vite')).href);
const { viteSingleFile } = await import(pathToFileURL(requirePlugin.resolve('vite-plugin-singlefile')).href);
const runtime = `${root}runtime`;
await mkdir(runtime, { recursive: true });
const serverResult = await build({ absWorkingDir: root, entryPoints: ['src/server/index.ts'], outfile: `${runtime}/server.mjs`, bundle: true, platform: 'node', target: 'node24', format: 'esm', metafile: true, banner: { js: '// Generated by tooling/build-agentero-studio.mjs. Edit src/server, src/core, or src/contracts instead.\nimport { createRequire as __createRequire } from "node:module"; const require = __createRequire(import.meta.url);' } });
await copyFile(requirePlugin.resolve('@resvg/resvg-wasm/index_bg.wasm'), `${runtime}/resvg.wasm`);
let appInputs = [];
await viteBuild({ configFile: false, root: `${root}src/app`, plugins: [sdkProtocolDebugPlugin(transform), viteSingleFile(), { name: 'studio-runtime-inputs', generateBundle() { appInputs = [...this.getModuleIds()]; } }], build: { outDir: runtime, emptyOutDir: false, target: 'es2023', sourcemap: false, reportCompressedSize: false } });
const html = await readFile(`${runtime}/index.html`, 'utf8');
await writeFile(`${runtime}/app.html`, html.endsWith('\n') ? html : `${html}\n`);
await unlink(`${runtime}/index.html`);
const packages = new Map();
for (let input of [...Object.keys(serverResult.metafile.inputs), ...appInputs, requirePlugin.resolve('@resvg/resvg-wasm/index_bg.wasm')]) {
  input = input.replace(/^\0+/, '').split('?')[0];
  if (!input.replaceAll('\\', '/').includes('node_modules/')) continue;
  let directory;
  try { directory = dirname(await realpath(isAbsolute(input) ? input : resolve(root, input))); } catch { continue; }
  while (directory !== dirname(directory)) {
    try {
      const info = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
      if (info.name && info.version) {
        let packageRoot = directory;
        for (let ancestor = dirname(directory); ancestor !== dirname(ancestor) && !ancestor.endsWith('node_modules'); ancestor = dirname(ancestor)) {
          try { const outer = JSON.parse(await readFile(join(ancestor, 'package.json'), 'utf8')); if (outer.name === info.name && outer.version === info.version) packageRoot = ancestor; else if (outer.name && outer.version) break; } catch { /* Subdirectories may repeat a package identity. */ }
        }
        packages.set(`${info.name}@${info.version}`, { ...info, directory: packageRoot }); break;
      }
    } catch { /* A module directory needn't be a package root. */ }
    directory = dirname(directory);
  }
}
const notices = [];
for (const [identity, info] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  const destination = `${root}assets/licenses/packages/${info.name.replaceAll('/', '__')}/${info.version}`;
  await mkdir(destination, { recursive: true });
  const files = (await readdir(info.directory)).filter(name => /^(LICENSE|LICENCE|NOTICE|COPYING|COPYRIGHT)(?:\.|$)/i.test(name) && !/\.(?:js|ts|json|wasm)$/i.test(name));
  if (!files.length && identity === '@resvg/resvg-wasm@2.6.2') {
    const source = `${root}assets/licenses/sources/resvg-wasm/2.6.2/LICENSE`;
    const bytes = await readFile(source);
    if (createHash('sha256').update(bytes).digest('hex') !== '4b89d4518bd135ab4ee154a7bce722246b57a98c3d7efc1a09409898160c2bd1') throw new Error('Pinned resvg license bytes changed.');
    await copyFile(source, join(destination, 'LICENSE'));
    files.push('LICENSE');
    notices.push({ name: info.name, version: info.version, license: info.license, files, source: 'https://github.com/yisibl/resvg-js/tree/9ca058462ac529120c8cc84ddcd6fef644cc5406' });
    continue;
  }
  if (!files.length) throw new Error(`No distributable license text for ${identity}`);
  for (const name of files) await copyFile(join(info.directory, name), join(destination, name));
  notices.push({ name: info.name, version: info.version, license: info.license, files });
}
await writeFile(`${root}assets/licenses/manifest.json`, `${JSON.stringify(notices, null, 2)}\n`);
console.log('Built Agentero Studio marketplace runtime: server.mjs, app.html, resvg.wasm');
